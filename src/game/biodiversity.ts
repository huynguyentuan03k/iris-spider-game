// Helper matching worldGen.ts projection: lon [-175..180] -> [0..320], lat [78..-76] -> [0..180]
function earthLonLatToTile(lon: number, lat: number): { tx: number; ty: number } {
  const tx = Math.max(4, Math.min(315, Math.round(((lon + 175) / 355) * 320)));
  const ty = Math.max(4, Math.min(175, Math.round(((78 - lat) / 154) * 180)));
  return { tx, ty };
}

